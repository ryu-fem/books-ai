"""
مطابقة ذكية باستخدام Groq API - مجاني بالكامل. الشرط الأساسي: لازم يتحقق
مع بعض (المرحلة الدراسية + المادة) عشان أي كتاب يتحسب مطابق، ولو اتحققوا
بيرجع كل الكتب المطابقة (كل الأجزاء) مش كتاب واحد بس.

ملحوظة عن الموديل: كان مستخدم llama-3.3-70b-versatile، لكن Groq أعلنت
إيقافه (deprecated) على الباقة المجانية/Developer في يونيو 2026، والبديل
الرسمي اللي بتوصي بيه Groq نفسها هو openai/gpt-oss-120b - موديل مفتوح
المصدر وقوي في الاستدلال (reasoning)، ولسه مجاني بالكامل على Groq.
"""

import os
import re

import requests

from grading import detect_grade

GROQ_API_URL = "https://api.groq.com/openai/v1/chat/completions"
# openai/gpt-oss-120b: البديل اللي Groq نفسها بتوصي بيه بدل
# llama-3.3-70b-versatile (اتوقف على الباقة المجانية)، وبيدي دقة أعلى في
# اتباع تعليمات صارمة زي شرط "المرحلة + المادة مع بعض".
MODEL_NAME = os.environ.get("GROQ_MODEL", "openai/gpt-oss-120b")


class AIMatchUnavailable(Exception):
    """بترفع لما الـ AI مش قادر يستجيب أصلاً (مفتاح مفقود، مشكلة نت، حد
    الطلبات اتعدى..) - مختلف عن إن الـ AI رد بس قال مفيش تطابق."""


def ai_pick_books(query: str, books: list):
    """
    books: list of tuples (id, title, file_id, file_name)
    بيرجع list فيها كل الـ book_id اللي فعلاً مطابقين لطلب المستخدم، بشرط
    إن الاتنين دول يتحققوا مع بعض:
      1) المرحلة/السنة الدراسية
      2) المادة
    لو الرسالة مذكرتش مرحلة أو مادة واضحة، أو مفيش كتب تطابق الشرطين مع
    بعض، بترجع [] (قائمة فاضية - ده رد شرعي، مش خطأ).
    بترمي AIMatchUnavailable لو الـ API نفسه فشل يستجيب أصلاً.
    """
    if not books or not query.strip():
        return []

    api_key = os.environ.get("GROQ_API_KEY")
    if not api_key:
        raise AIMatchUnavailable("GROQ_API_KEY مش متظبط")

    listing = "\n".join(f"{b[0]}. [{detect_grade(b[1])}] {b[1]}" for b in books)
    prompt = (
        "انت مساعد بيحدد كل الكتب اللي تطابق طلب المستخدم من قائمة كتب "
        "مدرسية متاحة. كل كتاب قدامه تصنيف المرحلة الدراسية بين قوسين "
        "معمول بشكل آلي، ممكن يكون \"غير مصنّف\" لو مقدرش يحدد.\n\n"
        "شرط أساسي وصارم: الكتاب يتحسب مطابق للطلب لو وبس لو اتحقق الشرطين "
        "دول مع بعض في نفس الوقت:\n"
        "1) المرحلة/السنة الدراسية اللي المستخدم طلبها (أو فهمت ضمنيًا من "
        "رسالته)\n"
        "2) المادة الدراسية أو اسم الكتاب اللي المستخدم طلبه\n\n"
        "لو الرسالة مفيهاش تحديد واضح (ولو ضمني) للمرحلة، أو مفيهاش تحديد "
        "واضح للمادة/الاسم، متختارش أي كتاب خالص - رد 0.\n\n"
        "لو الشرطين اتحققوا، رجّع كل الكتب اللي مادتهم ومرحلتهم متطابقين "
        "(كل الأجزاء/الفصول المتاحة لنفس المادة ونفس المرحلة)، مش كتاب "
        "واحد بس.\n\n"
        "خد بالك إن عناوين الكتب ممكن يكون فيها أخطاء إملائية بسيطة (زي "
        "\"ثاموي\" بدل \"ثانوي\")، ده ميمنعكش من المطابقة الصحيحة.\n\n"
        "مثال 1 (مرحلة مختلفة بترفض حتى لو المادة زي بعض):\n"
        "قائمة الكتب:\n"
        "1. [تانية ثانوي (بكالوريا)] كتاب الجيم انجليزي تانيه ثانوي "
        "بكالوريا ( 1ج )\n"
        "2. [تانية ثانوي (بكالوريا)] كتاب الجيم انجليزي تانيه ثانوي "
        "بكالوريا ( 2ج )\n"
        "3. [تالتة ثانوي] كتاب فايز انجليزي تالتة ثانوي\n"
        "رسالة المستخدم: \"عايز كتاب الجيم تانيه ثانوي بكالوريا\"\n"
        "الرد الصحيح: 1,2\n"
        "(لأن الاتنين نفس المرحلة ونفس اسم الكتاب، وكتاب رقم 3 مرحلة "
        "مختلفة فمابيترجعش رغم إنه نفس المادة)\n\n"
        "مثال 2 (نفس المرحلة بس مادة مختلفة بترفض):\n"
        "قائمة الكتب:\n"
        "4. [تالتة ثانوي] كتاب المعاصر فيزياء تالتة ثانوي\n"
        "5. [تالتة ثانوي] كتاب المعاصر كيمياء تالتة ثانوي\n"
        "رسالة المستخدم: \"محتاج كتاب فيزياء تالتة ثانوي\"\n"
        "الرد الصحيح: 4\n"
        "(كتاب رقم 5 نفس المرحلة بالظبط بس مادة مختلفة، فمابيترجعش)\n\n"
        f'رسالة المستخدم الحقيقية: "{query}"\n\n'
        f"قائمة الكتب المتاحة (رقم. [المرحلة] العنوان):\n{listing}\n\n"
        "اكتب سطر واحد بس في الآخر بأرقام كل الكتب المطابقة مفصولة "
        "بفاصلة، من غير أي كلام إضافي (مثال: 8,9). لو مفيش أي كتاب "
        "يستحق المطابقة حسب القواعد فوق، اخر سطر يكون الرقم 0 بالظبط "
        "ولا حاجة تانية معاه."
    )

    try:
        response = requests.post(
            GROQ_API_URL,
            headers={
                "Authorization": f"Bearer {api_key}",
                "Content-Type": "application/json",
            },
            json={
                "model": MODEL_NAME,
                "messages": [{"role": "user", "content": prompt}],
                # gpt-oss بيستهلك جزء من الـ tokens في التفكير الداخلي
                # (reasoning) قبل الرد النهائي، فمحتاجين مساحة أكبر من
                # الموديلات القديمة عشان الرد النهائي مايتقطعش.
                "max_completion_tokens": 300,
                "temperature": 0,
                # تفكير خفيف يكفي لمهمة تصنيف بسيطة زي دي، وبيقلل
                # زمن/تكلفة الاستجابة.
                "reasoning_effort": "low",
            },
            timeout=25,
        )
        response.raise_for_status()
        data = response.json()
        message = data["choices"][0]["message"]
        # gpt-oss بيرجع تفكيره الداخلي في حقل "reasoning" منفصل عن الرد
        # النهائي في "content" - فبنعتمد على content بس.
        text = (message.get("content") or "").strip()
    except Exception as exc:
        # أي مشكلة (نت، مفتاح غلط، تعدي حد الطلبات..) = الموديل مش متاح
        raise AIMatchUnavailable(str(exc)) from exc

    if not text:
        raise AIMatchUnavailable("رد الموديل جه فاضي (ممكن يكون استهلك كل الـ tokens في التفكير)")

    # الرد النهائي المفروض يكون آخر سطر غير فاضي (زي "8,9" أو "0"). بناخد
    # آخر سطر فيه أرقام عشان نتجنب أي كلام تفكير إضافي لو حصل وطلع في
    # الـ content غلط.
    lines = [ln.strip() for ln in text.splitlines() if ln.strip()]
    answer_line = lines[-1] if lines else text

    valid_ids = {b[0] for b in books}
    found_ids = [int(n) for n in re.findall(r"\d+", answer_line)]
    # 0 مش رقم كتاب حقيقي فهيتفلتر تلقائي هنا
    result_ids = [n for n in found_ids if n in valid_ids]

    print(f"[ai_matcher] query={query!r} raw_response={text!r} -> book_ids={result_ids}")
    return result_ids
