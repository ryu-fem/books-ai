"""
كشف المرحلة الدراسية والمادة من نص العنوان/الرسالة.

الهدف: نقدر نفلتر الكتب كودياً (مش بس نسيب القرار كله للـ AI) بشرط إن
المرحلة الدراسية *و* المادة الاتنين يتطابقوا. الفلترة هنا "متحفظة": بترفض
كتاب بس لو واثقة إن المرحلة أو المادة مختلفة فعلاً. لو مقدرتش تحدد حاجة
(مرحلة أو مادة) من النص، بترجع None وتسيب القرار للـ AI بدل ما ترفض غلط.
"""

import re

# التشكيل + التطويل - بنشيلهم عشان "الفِيزياء" و"الفيـزياء" يتعاملوا زي "الفيزياء"
_DIACRITICS = re.compile("[\u064B-\u065F\u0670\u0640]")
_ARABIC_DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩", "0123456789")


def _normalize(text: str) -> str:
    t = text.lower()  # عشان English / english يتطابقوا
    t = _DIACRITICS.sub("", t)
    t = t.translate(_ARABIC_DIGITS)
    t = t.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")
    t = t.replace("ة", "ه")
    t = t.replace("ى", "ي")
    return t


# نسخة عامة من نفس الدالة، عشان الملفات التانية (البوت والـ AI) تستخدمها
# في المقارنات النصية بدل ما كل واحد يعمل تطبيع مختلف.
normalize_text = _normalize


# ---------------- المرحلة الدراسية ----------------

_PRIMARY_YEARS = [
    ("سادسه", "سادسة ابتدائي"),
    ("خامسه", "خامسة ابتدائي"),
    ("رابعه", "رابعة ابتدائي"),
    ("تالته", "تالتة ابتدائي"),
    ("تانيه", "تانية ابتدائي"),
    ("اولي", "أولى ابتدائي"),
    ("اول", "أولى ابتدائي"),
]

_PREP_YEARS = [
    ("تالته", "تالتة اعدادي"),
    ("تانيه", "تانية اعدادي"),
    ("اولي", "أولى اعدادي"),
    ("اول", "أولى اعدادي"),
]


def detect_grade(title: str) -> str:
    """بيحدد الصف الدراسي من نص العنوان نفسه، عشان نقدر نعرض الكتب مجمّعة
    ونوضح للـ AI مرحلة كل كتاب، من غير ما نحتاج المالك يضيف تصنيف يدوي."""
    return _detect_grade_from_text(title)


def detect_query_grade(text: str):
    """بيحاول يحدد المرحلة المطلوبة من نص رسالة المستخدم نفسها. بيرجع
    None لو الرسالة معملتش تحديد واضح للمرحلة."""
    grade = _detect_grade_from_text(text)
    return None if grade == "غير مصنّف" else grade


def _detect_grade_from_text(text: str) -> str:
    t = _normalize(text)

    if "ثانو" in t:
        if "تالت" in t:
            return "تالتة ثانوي"
        if "اول" in t:
            return "أولى ثانوي"
        if "تاني" in t:
            if "مش بكالوريا" in t or "مش بكالوريه" in t:
                return "تانية ثانوي (مش بكالوريا)"
            if "بكالوريا" in t or "بكالوريه" in t:
                return "تانية ثانوي (بكالوريا)"
            return "تانية ثانوي"
        return "غير مصنّف"

    if "اعدادي" in t or "اعداديه" in t:
        for key, label in _PREP_YEARS:
            if key in t:
                return label
        return "غير مصنّف"

    if "ابتدائي" in t or "ابتدائيه" in t or "ابتدا" in t:
        for key, label in _PRIMARY_YEARS:
            if key in t:
                return label
        return "غير مصنّف"

    return "غير مصنّف"


def grade_matches(book_grade: str, query_grade) -> bool:
    """بيتأكد إن مرحلة الكتاب بتتطابق مع المرحلة المطلوبة في رسالة
    المستخدم. لو المستخدم قال "تانية ثانوي" من غير تحديد بكالوريا/مش
    بكالوريا، بيتقبل أي كتاب من مرحلة "تانية ثانوي" بغض النظر عن التفصيلة
    دي."""
    if query_grade is None:
        return True
    if book_grade == query_grade:
        return True
    if query_grade == "تانية ثانوي" and book_grade.startswith("تانية ثانوي"):
        return True
    return False


# ---------------- المادة الدراسية ----------------
# كل مادة ليها قائمة كلمات مفتاحية (بعد التطبيع). لو أي كلمة منها موجودة
# في النص، يبقى المادة دي متحققة. الترتيب مهم: مواد أكتر تحديدًا (زي
# "علم نفس") قبل مواد عامة ممكن تتداخل معاها بالغلط.
_SUBJECT_KEYWORDS = [
    ("انجليزي", ["انجليزي", "انجليزى", "english"]),
    ("فرنساوي", ["فرنساوي", "فرنساوى", "فرنسي", "لغه فرنسيه", "french"]),
    ("الماني", ["الماني", "الالمانيه", "german"]),
    ("عربي", ["لغه عربيه", "نصوص", "قواعد النحو", "بلاغه"]),
    ("فيزياء", ["فيزياء", "فيزيا"]),
    ("كيمياء", ["كيمياء", "كيميا"]),
    ("احياء", ["احياء", "الاحياء"]),
    ("جيولوجيا", ["جيولوجيا", "علم البيئه"]),
    ("رياضيات", ["رياضه", "رياضيات", "جبر", "هندسه", "تفاضل وتكامل",
                 "احصاء ورياضه", "استاتيكا", "ديناميكا"]),
    ("احصاء واقتصاد", ["احصاء", "اقتصاد"]),
    ("تاريخ", ["تاريخ"]),
    ("جغرافيا", ["جغرافيا"]),
    ("فلسفه ومنطق", ["فلسفه", "منطق"]),
    ("علم نفس واجتماع", ["علم نفس", "علم الاجتماع"]),
    ("دراسات اجتماعيه", ["دراسات اجتماعيه"]),
    ("علوم", ["علوم"]),
    ("حاسب الي", ["حاسب الي", "حاسب آلي", "كمبيوتر"]),
    ("تربيه دينيه", ["تربيه دينيه", "دين اسلامي", "دين مسيحي", "تربيه اسلاميه"]),
    ("تربيه وطنيه", ["تربيه وطنيه"]),
]


# بادئات عربية شائعة ممكن تسبق اسم المادة (الفيزياء، بالفيزياء، للفيزياء..)
_PREFIX = r"(?:وال|بال|لل|ال|و|ب|ل)?"


def _has_keyword(normalized_text: str, keyword: str) -> bool:
    """بيدور على الكلمة المفتاحية كبداية كلمة (مع السماح ببادئة زي "ال")،
    مش كجزء عشوائي جوه كلمة تانية - عشان "معلومات" مثلاً ماتتحسبش مادة
    "علوم"."""
    pattern = r"(?<!\w)" + _PREFIX + re.escape(_normalize(keyword))
    return re.search(pattern, normalized_text) is not None


def detect_subject(text: str):
    """بيحاول يحدد المادة الدراسية من النص (عنوان كتاب أو رسالة مستخدم).
    بيرجع اسم المادة لو لقى كلمة مفتاحية واضحة، أو None لو مقدرش يحدد -
    وده مقصود عشان مانرفضش كتاب غلط بس لأن الكلمة اللي استخدمها المالك في
    العنوان مش موجودة في القاموس."""
    t = _normalize(text)
    for subject, keywords in _SUBJECT_KEYWORDS:
        for kw in keywords:
            if _has_keyword(t, kw):
                return subject
    return None


def subject_matches(book_subject, query_subject) -> bool:
    """زي grade_matches بالظبط بس للمادة: بترفض بس لما تكون واثقة إن
    المادتين اتحددوا وهما مختلفين. لو أي واحدة منهم None (مقدرناش نحددها)
    بنسيب القرار للـ AI ومنرفضش حاجة."""
    if query_subject is None or book_subject is None:
        return True
    return book_subject == query_subject
